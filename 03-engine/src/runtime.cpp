// UTF-8 decoder shared by input validation and streaming output. Incomplete
// trailing characters stay buffered; invalid generated bytes use U+FFFD.
struct Codepoint { uint32_t cp; size_t bytes; bool incomplete; bool valid; };
Codepoint codepoint(const std::string& s, size_t p) {
    unsigned char c = s[p];
    if (c < 0x80) return {c, 1, false, true};
    int n = c >= 0xc2 && c <= 0xdf ? 2 : c >= 0xe0 && c <= 0xef ? 3 : c >= 0xf0 && c <= 0xf4 ? 4 : 0;
    if (!n) return {0xfffd, 1, false, false};
    uint32_t cp = c & ((1u << (7-n))-1);
    for (int i = 1; i < n; ++i) {
        if (p+size_t(i) == s.size()) return {0xfffd, size_t(i), true, false};
        unsigned char b = s[p+i];
        if ((b & 0xc0) != 0x80 || (i == 1 && ((c == 0xe0 && b < 0xa0) || (c == 0xed && b >= 0xa0) || (c == 0xf0 && b < 0x90) || (c == 0xf4 && b >= 0x90))))
            return {0xfffd, size_t(i), false, false};
        cp = (cp << 6) | (b & 63);
    }
    return {cp, size_t(n), false, true};
}
std::string consume_utf8(std::string& buffer, bool final) {
    std::string out; size_t p = 0;
    while (p < buffer.size()) {
        auto c = codepoint(buffer, p);
        if (c.incomplete && !final) break;
        if (c.valid) out.append(buffer, p, c.bytes); else append_utf8(out, 0xfffd);
        p += c.bytes;
    }
    buffer.erase(0, p); return out;
}

class Reader {
    std::ifstream f;
    uint64_t remaining;
public:
    explicit Reader(const std::string& path) : f(std::filesystem::u8path(path), std::ios::binary | std::ios::ate), remaining(0) {
        require(bool(f), "Cannot open model: " + path);
        remaining = uint64_t(f.tellg()); f.seekg(0);
        uint32_t endian = 1; require(*reinterpret_cast<char*>(&endian) == 1, "Little-endian CPU required");
    }
    void read(void* out, uint64_t n) {
        require(n <= remaining, "Truncated model file");
        f.read(static_cast<char*>(out), std::streamsize(n)); require(bool(f), "Model read failed"); remaining -= n;
    }
    template<class T> T scalar() { T x; read(&x, sizeof(T)); return x; }
    uint32_t count(uint32_t max) { auto n=scalar<uint32_t>(); require(n <= max, "Model count exceeds limit"); return n; }
    std::string string(uint32_t max=16*1024*1024) { auto n=count(max); require(n <= remaining, "Truncated string"); std::string s(n, '\0'); read(s.data(), n); return s; }
    uint64_t left() const { return remaining; }
};

// A persistent row-parallel worker pool; never spawns threads per matrix/token.
class Pool {
    std::vector<std::thread> workers;
    std::mutex mutex; std::condition_variable wake, done;
    std::function<void(size_t, size_t)> job;
    size_t total = 0, epoch = 0, pending = 0;
    bool closing = false;
    int count;
public:
    explicit Pool(int threads) : count(threads) {
        try {
            for (int id=1; id<count; ++id) workers.emplace_back([this,id] {
                size_t seen=0;
                for (;;) {
                    std::unique_lock<std::mutex> lock(mutex);
                    wake.wait(lock, [&]{return closing || epoch != seen;});
                    if (closing) return;
                    seen=epoch; size_t n=total; lock.unlock();
                    job(n*size_t(id)/size_t(count), n*size_t(id+1)/size_t(count));
                    lock.lock(); if (--pending == 0) done.notify_one();
                }
            });
        } catch (...) { {std::lock_guard<std::mutex> lock(mutex); closing=true;} wake.notify_all(); for(auto& w:workers) w.join(); throw; }
    }
    ~Pool() { {std::lock_guard<std::mutex> lock(mutex); closing=true;} wake.notify_all(); for(auto& w:workers) w.join(); }
    void run(size_t n, const std::function<void(size_t,size_t)>& fn) {
        if (count == 1 || n < 64) { fn(0,n); return; }
        {std::lock_guard<std::mutex> lock(mutex); job=fn; total=n; pending=workers.size(); ++epoch;}
        wake.notify_all(); fn(0,n/size_t(count));
        std::unique_lock<std::mutex> lock(mutex); done.wait(lock,[&]{return pending==0;});
    }
};

float dot(const float* a, const float* b, int n) {
    float sum=0; int i=0;
#if defined(__AVX2__)
    __m256 acc=_mm256_setzero_ps();
    for (; i+8<=n; i+=8) acc=_mm256_add_ps(acc,_mm256_mul_ps(_mm256_loadu_ps(a+i),_mm256_loadu_ps(b+i)));
    alignas(32) float tmp[8]; _mm256_store_ps(tmp,acc); for(float v:tmp) sum+=v;
#endif
    for (;i<n;++i) sum+=a[i]*b[i]; return sum;
}
float dot_q8(const int8_t* a, const float* b, int n) {
    float sum=0; int i=0;
#if defined(__AVX2__)
    __m256 acc=_mm256_setzero_ps();
    for (;i+8<=n;i+=8) {
        auto bytes=_mm_loadl_epi64(reinterpret_cast<const __m128i*>(a+i));
        auto values=_mm256_cvtepi32_ps(_mm256_cvtepi8_epi32(bytes));
        acc=_mm256_add_ps(acc,_mm256_mul_ps(values,_mm256_loadu_ps(b+i)));
    }
    alignas(32) float tmp[8]; _mm256_store_ps(tmp,acc); for(float v:tmp) sum+=v;
#endif
    for (;i<n;++i) sum+=float(a[i])*b[i]; return sum;
}
struct Tensor {
    std::vector<int> shape;
    Vec f, scale;
    std::vector<int8_t> q;
    bool quantized() const { return !q.empty(); }
    Vec row(int index) const {
        int n=shape.at(1); Vec out(n); size_t off=size_t(index)*n;
        for(int i=0;i<n;++i) out[i]=quantized() ? float(q[off+i])*scale[index] : f[off+i];
        return out;
    }
    Vec matvec(const Vec& x, Pool& pool) const {
        int rows=shape[0], cols=shape[1]; require(int(x.size())==cols, "Matrix input shape mismatch");
        Vec out(rows);
        pool.run(rows, [&](size_t begin,size_t end) {
            for(size_t i=begin;i<end;++i) out[i]=quantized() ? scale[i]*dot_q8(q.data()+i*cols,x.data(),cols) : dot(f.data()+i*cols,x.data(),cols);
        });
        return out;
    }
};
float sigmoid(float x) { return x >= 0 ? 1.f/(1.f+std::exp(-x)) : std::exp(x)/(1.f+std::exp(x)); }
float silu(float x) { return x*sigmoid(x); }
void norm(float* x, const float* weight, int n, float eps) {
    float factor=1.f/std::sqrt(dot(x,x,n)/float(n)+eps);
    for(int i=0;i<n;++i) x[i]=x[i]*factor*weight[i];
}
void normalize_l2(float* x,int n) { float f=1.f/std::sqrt(dot(x,x,n)+1e-6f); for(int i=0;i<n;++i) x[i]*=f; }
uint64_t pair_key(int a,int b) { return (uint64_t(uint32_t(a))<<32)|uint32_t(b); }

struct Tokenizer {
    std::vector<std::string> tokens;
    std::array<int,11> special;
    std::array<int,256> base;
    struct Range { uint32_t start,end; uint8_t kind; };
    std::vector<Range> ranges;
    struct Merge { int rank, token; };
    std::unordered_map<uint64_t,Merge> merges;
    int kind(uint32_t cp) const {
        auto it=std::upper_bound(ranges.begin(),ranges.end(),cp,[](uint32_t v,const Range& r){return v<r.start;});
        if(it==ranges.begin()) return 0; --it; return cp<=it->end ? it->kind : 0;
    }
    void bpe(const std::string& s, std::vector<int>& out) const {
        if(s.empty()) return;
        struct Node {int id,prev,next,version=0; bool alive=true;};
        struct Candidate {int rank,left,right,version,token; bool operator<(const Candidate& o) const { return rank!=o.rank ? rank>o.rank : left>o.left; }};
        std::vector<Node> nodes; nodes.reserve(s.size());
        for(unsigned char b:s) { require(base[b]>=0, "Input byte absent from training tokenizer: " + std::to_string(b)); int i=int(nodes.size()); nodes.push_back({base[b],i-1,i+1}); }
        nodes.back().next=-1;
        std::priority_queue<Candidate> queue;
        auto offer=[&](int i) { if(i<0 || nodes[i].next<0) return; int j=nodes[i].next; auto found=merges.find(pair_key(nodes[i].id,nodes[j].id)); if(found!=merges.end()) queue.push({found->second.rank,i,j,nodes[i].version,found->second.token}); };
        for(int i=0;i<int(nodes.size());++i) offer(i);
        while(!queue.empty()) {
            auto c=queue.top(); queue.pop(); auto& a=nodes[c.left]; auto& b=nodes[c.right];
            if(!a.alive || !b.alive || a.next!=c.right || a.version!=c.version) continue;
            // A neighbor can change its token without changing this node's version.
            auto found=merges.find(pair_key(a.id,b.id));
            if(found==merges.end() || found->second.rank!=c.rank) continue;
            a.id=c.token; ++a.version; a.next=b.next; b.alive=false;
            if(a.next>=0) nodes[a.next].prev=c.left;
            offer(a.prev); offer(c.left);
        }
        for(int i=0;i>=0;i=nodes[i].next) out.push_back(nodes[i].id);
    }
    void ordinary(const std::string& text,std::vector<int>& out) const {
        std::vector<uint32_t> cp; std::vector<size_t> offsets{0}; std::vector<int> kinds;
        for(size_t p=0;p<text.size();) { auto c=codepoint(text,p); require(c.valid,"Input is not valid UTF-8"); cp.push_back(c.cp); kinds.push_back(kind(c.cp)); p+=c.bytes; offsets.push_back(p); }
        size_t i=0,n=cp.size();
        while(i<n) {
            size_t start=i, end=i;
            if(cp[i]=='\'') {
                for(const std::string suffix : {"s","t","re","ve","m","ll","d"}) {
                    bool match=i+1+suffix.size()<=n;
                    for(size_t k=0;match && k<suffix.size();++k) match=cp[i+1+k]==uint32_t(suffix[k]);
                    if(match) {end=i+1+suffix.size(); break;}
                }
            }
            if(end==i) {
                size_t lead=(cp[i]==' ' && i+1<n && kinds[i+1]!=3) ? i+1 : i;
                if(kinds[lead]!=3) { int k=kinds[lead]; end=lead+1; while(end<n && kinds[end]==k) ++end; }
                else { end=i+1; while(end<n && kinds[end]==3) ++end; if(end<n && end-i>1) --end; }
            }
            bpe(text.substr(offsets[start],offsets[end]-offsets[start]),out); i=end;
        }
    }
    std::vector<int> encode(const std::string& text) const {
        std::vector<int> out; size_t pos=0;
        while(pos<text.size()) {
            size_t next=std::string::npos; int found=-1;
            for(int i=0;i<11;++i) { auto p=text.find(specials[i],pos); if(p<next) {next=p; found=i;} }
            if(found<0) {ordinary(text.substr(pos),out); break;}
            ordinary(text.substr(pos,next-pos),out); out.push_back(special[found]); pos=next+specials[found].size();
        }
        return out;
    }
};
