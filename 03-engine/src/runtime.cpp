Vec Runtime::forward(int token,bool logits) {
    auto& m=*impl; require(token>=0 && token<m.vocab,"Token ID out of range"); require(m.seen<m.capacity,"Context exhausted; reset or use a shorter prompt");
    Vec x=m.tensor("embedding.weight").row(token);
    for(int i=0;i<m.layers;++i) {
        std::string p="layers."+std::to_string(i)+"."; Vec normalized=x;
        norm(normalized.data(),m.tensor(p+"attn_norm.weight").f.data(),m.hidden,m.eps);
        auto mixed=(i+1)%m.interval==0 ? m.attention(p+"mixer.",normalized,m.states[i]) : m.delta(p+"mixer.",normalized,m.states[i]);
        for(int j=0;j<m.hidden;++j) x[j]+=mixed[j];
        normalized=x; norm(normalized.data(),m.tensor(p+"ffn_norm.weight").f.data(),m.hidden,m.eps);
        auto up=m.linear(p+"ffn.gate_up",normalized); Vec activated(m.intermediate);
        for(int j=0;j<m.intermediate;++j) activated[j]=silu(up[j])*up[m.intermediate+j];
        auto down=m.linear(p+"ffn.down",activated); for(int j=0;j<m.hidden;++j) x[j]+=down[j];
    }
    ++m.seen;
    if(!logits) return {};
    norm(x.data(),m.tensor("final_norm.weight").f.data(),m.hidden,m.eps);
    return m.tensor(m.tied ? "embedding.weight" : "lm_head.weight").matvec(x,m.pool);
}
