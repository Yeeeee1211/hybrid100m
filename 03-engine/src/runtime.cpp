std::vector<int> Runtime::chat_prompt(const std::vector<Message>& messages,bool thinking) const {
    require(!messages.empty() && messages.back().role=="user","Chat must end with a user message");
    const auto& t=impl->tokenizer.special; std::vector<int> out{t[1]};
    auto append=[&](const std::string& text) {auto ids=encode(text); out.insert(out.end(),ids.begin(),ids.end());};
    for(const auto& message:messages) {
        require(message.role=="system" || message.role=="user" || message.role=="assistant","Unsupported message role");
        out.push_back(t[3]); append(message.role+"\n"); if(message.role=="assistant") {out.push_back(t[6]); out.push_back(t[9]);}
        append(message.content); if(message.role=="assistant") out.push_back(t[10]); out.push_back(t[4]);
    }
    out.push_back(t[3]); append("assistant\n"); out.push_back(t[thinking ? 5 : 6]); out.push_back(t[thinking ? 7 : 9]); return out;
}

void GenerationOptions::validate() const {
    require(max_tokens>0 && max_tokens<=131072,"max_tokens must be in [1,131072]"); require(max_think_tokens>=0,"max_think_tokens must be nonnegative");
    require(std::isfinite(temperature) && temperature>=0,"temperature must be finite and nonnegative"); require(std::isfinite(top_p) && top_p>0 && top_p<=1,"top_p must be in (0,1]");
    require(top_k>=0,"top_k must be nonnegative"); require(std::isfinite(repeat_penalty) && repeat_penalty>=1,"repeat_penalty must be >= 1"); require(repeat_last_n>=0,"repeat_last_n must be nonnegative");
    require(stop.size()<=16,"At most 16 stop strings"); for(const auto& s:stop) require(!s.empty() && s.size()<=4096,"Invalid stop string");
}
