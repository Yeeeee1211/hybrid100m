GenerationOptions parse_options(const Json& value) {
    GenerationOptions o;
    if(value.has("max_tokens")) o.max_tokens=value.at("max_tokens").integer();
    if(value.has("max_think_tokens")) o.max_think_tokens=value.at("max_think_tokens").integer();
    if(value.has("temperature")) o.temperature=value.at("temperature").number();
    if(value.has("top_k")) o.top_k=value.at("top_k").integer();
    if(value.has("top_p")) o.top_p=value.at("top_p").number();
    if(value.has("repeat_penalty")) o.repeat_penalty=value.at("repeat_penalty").number();
    if(value.has("repeat_last_n")) o.repeat_last_n=value.at("repeat_last_n").integer();
    if(value.has("seed")) {int n=value.at("seed").integer(); require(n>=0,"seed must be nonnegative"); o.seed=uint32_t(n);}
    if(value.has("enable_thinking")) o.thinking=value.at("enable_thinking").boolean();
    if(value.has("stop") && !value.at("stop").null()) {const auto& s=value.at("stop"); if(s.is_string()) o.stop.push_back(s.str()); else for(const auto& x:s.array()) o.stop.push_back(x.str());}
    o.validate(); return o;
}
